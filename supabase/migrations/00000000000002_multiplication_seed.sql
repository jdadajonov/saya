    '10000000-0000-0000-0000-000000000008',
    '10000000-0000-0000-0000-000000000009',
    '10000000-0000-0000-0000-000000000010'
  ];
  a INT; b INT; diff SMALLINT;
BEGIN
  FOR a IN 1..9 LOOP
    FOR b IN 1..9 LOOP
      diff := CASE WHEN GREATEST(a, b) <= 3 THEN 1
                   WHEN GREATEST(a, b) <= 6 THEN 2
                   ELSE 3 END;
      INSERT INTO exercises (skill_id, type, payload, difficulty, locale)
      VALUES (
        skill_ids[a],
        'multiplication.fill_blank',
        jsonb_build_object('a', a, 'b', b, 'answer', a * b),
        diff,
        'any'
      );
    END LOOP;
  END LOOP;
END;
$$;
